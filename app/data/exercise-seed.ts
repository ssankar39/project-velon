import type { Exercise } from '@/app/types/workout';

// Compact helper – creates an Exercise record with defaults filled in
function ex(
  name: string,
  aliases: string[],
  primary: Exercise['primaryMuscles'],
  secondary: Exercise['secondaryMuscles'],
  pattern: Exercise['movementPattern'],
  equip: Exercise['equipment'],
  repRange: [number, number],
  diff: Exercise['difficulty'],
  category: string,
  instructions: string,
  variations?: string[],
): Omit<Exercise, '_id' | 'createdAt' | 'updatedAt'> {
  return {
    name, aliases, primaryMuscles: primary, secondaryMuscles: secondary,
    movementPattern: pattern, equipment: equip,
    defaultRepRange: { min: repRange[0], max: repRange[1] },
    difficulty: diff, category, instructions, isCustom: false,
    variations: variations ?? [],
  };
}

